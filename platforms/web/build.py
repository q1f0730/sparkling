def head_html():
    L = ['<!-- pf:begin (generated by platforms/web/build.py; do not edit by hand) -->',
         '<link rel="manifest" href="/manifest.webmanifest">',
         '<meta name="theme-color" content="#1c1b18" media="(prefers-color-scheme: dark)">',
         '<meta name="mobile-web-app-capable" content="yes">',
         '<meta name="apple-mobile-web-app-capable" content="yes">',
         '<meta name="apple-mobile-web-app-title" content="Sparkling">',
         '<meta name="apple-mobile-web-app-status-bar-style" content="default">',
         '<meta name="application-name" content="Sparkling">',
         '<link rel="icon" type="image/png" sizes="32x32" href="/icons/favicon-32.png">',
         '<link rel="apple-touch-icon" sizes="180x180" href="/icons/apple-touch-icon-180.png">']
    for w, h, r in SPLASH:
        L.append(f'<link rel="apple-touch-startup-image" media="(device-width: {w}px) and (device-height: {h}px) and (-webkit-device-pixel-ratio: {r}) and (orientation: portrait)" href="/splash/splash-{w*r}x{h*r}.png">')
    L.append("<script>" + DETECT.replace("\n", "") + "</script>")
    L.append('<link rel="stylesheet" href="/pf.css">')
    L.append('<script src="/pf.js" defer></script>')
    L.append("<!-- pf:end -->")
    return "\n".join(L)

def build():
    css, js, sw = rd("pf.css"), rd("pf.js"), rd("sw.js")
    assets = {}
    for f in ICON_FILES:
        assets["/icons/" + f] = open(os.path.join(D, "icons", f), "rb").read()
    assets["/apple-touch-icon.png"] = assets["/icons/apple-touch-icon-180.png"]
    for w, h, r in SPLASH:
        n = f"splash-{w*r}x{h*r}.png"; assets["/splash/" + n] = open(os.path.join(D, "splash", n), "rb").read()
    h = hashlib.sha256()
    for part in (css, js, sw, json.dumps(MANIFEST)): h.update(part.encode())
    for k in sorted(assets): h.update(assets[k])
    ver = h.hexdigest()[:10]
    sw = sw.replace("__VERSION__", ver)
    text = {"/pf.css": ("text/css; charset=utf-8", css), "/pf.js": ("application/javascript; charset=utf-8", js),
            "/sw.js": ("application/javascript; charset=utf-8", sw),
            "/manifest.webmanifest": ("application/manifest+json", json.dumps(MANIFEST, indent=1))}
    out = ["// GENERATED by platforms/web/build.py. Do not edit. Platform layer: PWA manifest, service worker, icons, glass theme.",
           f'export const PWA_VERSION = "{ver}";',
           "const T = " + json.dumps(text) + ";",
           "const B = {"]
    for k, v in assets.items():
        out.append(f'  {json.dumps(k)}: "{base64.b64encode(v).decode()}",')
    out.append("};")
    out.append('''const bin = (b64) => { const s = atob(b64); const u = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) u[i] = s.charCodeAt(i); return u; };
export function pwaAsset(url) {
  const p = url.pathname;
  if (T[p]) {
    const [type, body] = T[p];
    const h = { "content-type": type, "cache-control": p === "/sw.js" ? "no-cache" : "public, max-age=300" };
    if (p === "/sw.js") h["service-worker-allowed"] = "/";
    return new Response(body, { headers: h });
  }
  if (p === "/favicon.ico") return new Response(bin(B["/icons/favicon-32.png"]), { headers: { "content-type": "image/png", "cache-control": "public, max-age=86400" } });
  if (B[p]) return new Response(bin(B[p]), { headers: { "content-type": "image/png", "cache-control": "public, max-age=86400" } });
  return null;
}''')
    open(os.path.join(ROOT, "src/pwa.js"), "w").write("\n".join(out) + "\n")
    open(os.path.join(D, "head.html"), "w").write(head_html() + "\n")
    print("src/pwa.js", os.path.getsize(os.path.join(ROOT, "src/pwa.js")), "bytes, version", ver)

def apply():
    p = os.path.join(ROOT, "src/app.html"); s = open(p, encoding="utf-8").read()
    block = head_html()
    if "<!-- pf:begin" in s:
        s = re.sub(r"<!-- pf:begin.*?<!-- pf:end -->", lambda m: block, s, flags=re.S)
    else:
        # drop the old inline data: favicon, the platform layer supplies PNG icons
        s = re.sub(r'<link rel="icon" href="data:image/svg\+xml[^"]*">\n?', "", s, count=1)
        i = s.index("</head>"); s = s[:i] + block + "\n" + s[i:]
    open(p, "w", encoding="utf-8").write(s)
    q = os.path.join(ROOT, "src/index.js"); j = open(q, encoding="utf-8").read()
    if "./pwa.js" not in j:
        j = j.replace('import APP from "./app.html";', 'import APP from "./app.html";\nimport { pwaAsset } from "./pwa.js";', 1)
        j = j.replace('      if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/media/")) return await api(req, env, ctx, url);',
                      '      if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/media/")) return await api(req, env, ctx, url);\n'
                      '      const asset = req.method === "GET" ? pwaAsset(url) : null;\n      if (asset) return asset;', 1)
        assert "pwaAsset(url)" in j, "index.js route patch failed"
        open(q, "w", encoding="utf-8").write(j)
    print("applied head block + index.js route")

if __name__ == "__main__":
    build()
    if len(sys.argv) > 1 and sys.argv[1] == "apply": apply()
